"""Supabase persistence helpers for the API tier.

All Supabase access for the model service is funneled through this module. The
FastAPI app calls these functions; it never talks to Supabase directly. The
Streamlit UI NEVER imports this module -- it does its one read-only query with
the anon key on its own side.

We store an input sequence's **sha256 hash and length** in `sequence_metadata`,
never the raw symbols (the "store hashes, not raw payloads" invariant). The
fitted Transformer lives in `run_artifacts` (not anon-readable).

Environment variables (set locally in a .env, and in the Render dashboard):
    SUPABASE_URL              -> https://<project-ref>.supabase.co
    SUPABASE_SERVICE_KEY      -> the service-role key (server-side only, secret!)
"""
from __future__ import annotations

import logging
import os
from typing import List, Optional

from supabase import Client, create_client

logger = logging.getLogger(__name__)

_client: Optional[Client] = None

_RUN_COLS = "id,dataset_id,lr,batch_size,epochs,accuracy,macro_f1,created_at"


def get_client() -> Client:
    """Lazily create and cache a Supabase client."""
    global _client
    if _client is None:
        url = os.environ["SUPABASE_URL"]
        key = os.environ["SUPABASE_SERVICE_KEY"]
        _client = create_client(url, key)
    return _client


def ping() -> bool:
    try:
        get_client().table("datasets").select("id").limit(1).execute()
        return True
    except Exception:
        return False


# ---------------------------------------------------------------------------
# datasets  (only the generation parameters -- sequences are regenerated by seed)
# ---------------------------------------------------------------------------
def insert_dataset(
    name: str, n_rows: int, seq_len: int, vocab_size: int, n_classes: int, seed: int
) -> dict:
    resp = (
        get_client()
        .table("datasets")
        .insert(
            {
                "name": name,
                "n_rows": n_rows,
                "seq_len": seq_len,
                "vocab_size": vocab_size,
                "n_classes": n_classes,
                "seed": seed,
            }
        )
        .execute()
    )
    return resp.data[0]


def get_dataset(dataset_id: int) -> Optional[dict]:
    resp = (
        get_client()
        .table("datasets")
        .select("*")
        .eq("id", dataset_id)
        .limit(1)
        .execute()
    )
    return resp.data[0] if resp.data else None


# ---------------------------------------------------------------------------
# runs  +  run_artifacts
# ---------------------------------------------------------------------------
def insert_run(
    dataset_id: int,
    lr: float,
    batch_size: int,
    epochs: int,
    metrics: dict,
    model_b64: str,
) -> dict:
    client = get_client()
    resp = (
        client.table("runs")
        .insert(
            {
                "dataset_id": dataset_id,
                "lr": lr,
                "batch_size": batch_size,
                "epochs": epochs,
                "accuracy": metrics["accuracy"],
                "macro_f1": metrics["macro_f1"],
            }
        )
        .execute()
    )
    run = resp.data[0]
    client.table("run_artifacts").insert(
        {"run_id": run["id"], "model_b64": model_b64}
    ).execute()
    return run


def get_run(run_id: int) -> Optional[dict]:
    resp = (
        get_client().table("runs").select(_RUN_COLS).eq("id", run_id).limit(1).execute()
    )
    return resp.data[0] if resp.data else None


def get_run_artifact(run_id: int) -> Optional[str]:
    resp = (
        get_client()
        .table("run_artifacts")
        .select("model_b64")
        .eq("run_id", run_id)
        .limit(1)
        .execute()
    )
    return resp.data[0]["model_b64"] if resp.data else None


def latest_runs(limit: int = 50) -> List[dict]:
    resp = (
        get_client()
        .table("runs")
        .select(_RUN_COLS)
        .order("created_at", desc=True)
        .limit(limit)
        .execute()
    )
    return resp.data


# ---------------------------------------------------------------------------
# sequence_metadata  (hash + length + prediction; NO raw symbols)
# ---------------------------------------------------------------------------
def insert_sequence_metadata(
    run_id: int,
    sha256: str,
    length: int,
    label: int,
    class_name: str,
    confidence: float,
) -> dict:
    resp = (
        get_client()
        .table("sequence_metadata")
        .insert(
            {
                "run_id": run_id,
                "sha256": sha256,
                "length": length,
                "label": label,
                "class_name": class_name,
                "confidence": confidence,
            }
        )
        .execute()
    )
    return resp.data[0]


# ===========================================================================
# TrioFormer: inputs / inferences / benchmarks  (db/migrations/002_trioformer.sql)
# ===========================================================================
# These helpers raise ``DatabaseError`` with a SANITIZED message. The raw
# exception is logged server-side (type + truncated text, never request
# headers) and chained as ``__cause__`` but is never put in an HTTP response.


class DatabaseError(RuntimeError):
    """A Supabase operation failed or Supabase is not configured."""


def _call(operation: str, fn):
    """Run ``fn()``; convert every failure into a sanitized ``DatabaseError``."""
    try:
        return fn()
    except DatabaseError:
        raise
    except KeyError as exc:  # get_client(): missing environment variable
        raise DatabaseError(
            "Database is not configured (SUPABASE_URL / SUPABASE_SERVICE_KEY missing)."
        ) from exc
    except Exception as exc:  # noqa: BLE001
        logger.warning("Supabase %s failed: %s: %.200s", operation, type(exc).__name__, exc)
        raise DatabaseError(f"Database operation '{operation}' failed.") from exc


def insert_inference(
    input_sha256: str, model_name: str, output: str, latency_ms: int
) -> dict:
    """Record one served inference.

    1. Upsert the prompt's SHA-256 into ``inputs`` (``ON CONFLICT DO NOTHING``;
       needs only INSERT privilege). Only the hash is stored -- never the prompt.
    2. Insert the ``inferences`` row; ``served_at`` is set by the database.

    The two statements are not one transaction (supabase-py has no multi-statement
    transactions); a failure of step 2 can leave an orphan hash row in ``inputs``,
    which is harmless. Returns the inserted row (``id``, ``served_at``, ...).
    """

    def run() -> dict:
        client = get_client()
        client.table("inputs").upsert(
            {"sha256": input_sha256}, on_conflict="sha256", ignore_duplicates=True
        ).execute()
        resp = (
            client.table("inferences")
            .insert(
                {
                    "input_sha256": input_sha256,
                    "model_name": model_name,
                    "output": output,
                    "latency_ms": latency_ms,
                }
            )
            .execute()
        )
        return resp.data[0]

    return _call("insert_inference", run)


def get_benchmarks() -> List[dict]:
    """Rows of the ``benchmarks`` materialized view (as of its last refresh)."""
    return _call(
        "get_benchmarks",
        lambda: get_client().table("benchmarks").select("*").order("model_name").execute().data,
    )


def get_benchmark_status() -> Optional[dict]:
    """The single ``benchmark_refresh_status`` row (actual last refresh metadata)."""

    def run() -> Optional[dict]:
        resp = get_client().table("benchmark_refresh_status").select("*").limit(1).execute()
        return resp.data[0] if resp.data else None

    return _call("get_benchmark_status", run)


def refresh_benchmarks() -> dict:
    """Call the ``refresh_benchmarks()`` SQL function (advisory-locked, concurrent-safe).

    Returns e.g. ``{"refreshed": true, "mode": "concurrent", "rows": 3, ...}`` or
    ``{"refreshed": false, "reason": "refresh_in_progress"}``.
    """
    return _call("refresh_benchmarks", lambda: get_client().rpc("refresh_benchmarks").execute().data)
